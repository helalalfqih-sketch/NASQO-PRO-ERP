// No unreviewed binary is downloaded. Build an isolated arm64 debug app only
// after supplying a reviewed Node 24 Android SDK with full node:sqlite support.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const sdk=process.env.NASQO_NODE_SDK_DIR,expected=process.env.NASQO_NODE_LIB_SHA256;
if(!sdk||!expected||!/^[a-f0-9]{64}$/.test(expected))throw new Error("Supply reviewed NASQO_NODE_SDK_DIR and NASQO_NODE_LIB_SHA256");
const lib=path.join(sdk,"lib","arm64-v8a","libnode.so"),headers=path.join(sdk,"include","node");
if(!fs.existsSync(path.join(headers,"node.h"))||!fs.existsSync(lib))throw new Error("SDK layout: include/node/node.h and lib/arm64-v8a/libnode.so");
if(crypto.createHash("sha256").update(fs.readFileSync(lib)).digest("hex")!==expected)throw new Error("Node library fingerprint mismatch");
const zip=path.join(root,"dist","original-web-runtime.zip");
if(!fs.existsSync(zip)||!fs.existsSync(zip+".sha256"))throw new Error("Run node mobile_runtime/prepare-bundle.mjs first");
const out=path.join(root,"dist","flutter-original-web");
if(fs.existsSync(out))throw new Error("Build directory already exists. Use a new checkout or move the generated directory aside.");
execFileSync("flutter",["create","--platforms=android","--org","com.indexesstore","--project-name","nasqo_original_web","--no-pub",out],{stdio:"inherit"});
const templates=path.join(root,"mobile_runtime","android");
const app=path.join(out,"android","app"),main=path.join(app,"src","main"),cpp=path.join(main,"cpp");
fs.copyFileSync(path.join(templates,"pubspec.yaml"),path.join(out,"pubspec.yaml"));
fs.copyFileSync(path.join(templates,"main.dart"),path.join(out,"lib","main.dart"));
fs.copyFileSync(path.join(templates,"MainActivity.kt"),path.join(main,"kotlin","com","indexesstore","nasqo_original_web","MainActivity.kt"));
fs.mkdirSync(cpp,{recursive:true});
for(const file of ["CMakeLists.txt","node_host.cpp"])fs.copyFileSync(path.join(templates,file),path.join(cpp,file));
const sdkDir=path.join(cpp,"node-sdk");
fs.mkdirSync(path.join(sdkDir,"include"),{recursive:true});
fs.cpSync(headers,path.join(sdkDir,"include","node"),{recursive:true});
fs.mkdirSync(path.join(sdkDir,"lib","arm64-v8a"),{recursive:true});
fs.copyFileSync(lib,path.join(sdkDir,"lib","arm64-v8a","libnode.so"));
const assets=path.join(main,"assets");fs.mkdirSync(assets,{recursive:true});
fs.copyFileSync(zip,path.join(assets,"original-web-runtime.zip"));
fs.copyFileSync(zip+".sha256",path.join(assets,"original-web-runtime.zip.sha256"));
const res=path.join(main,"res","xml");fs.mkdirSync(res,{recursive:true});
fs.copyFileSync(path.join(templates,"network_security_config.xml"),path.join(res,"network_security_config.xml"));
const manifest=path.join(main,"AndroidManifest.xml");
let xml=fs.readFileSync(manifest,"utf8");
if(!xml.includes("android.permission.INTERNET"))xml=xml.replace("<application",'<uses-permission android:name="android.permission.INTERNET" />\n    <application');
xml=xml.replace("<application",'<application android:networkSecurityConfig="@xml/network_security_config" android:allowBackup="false"');
fs.writeFileSync(manifest,xml);
const gradle=path.join(app,"build.gradle.kts");let g=fs.readFileSync(gradle,"utf8");
g=g.replace(/minSdk\s*=\s*(?:flutter\.minSdkVersion|\d+)/,"minSdk = 24").replace(/ndkVersion\s*=\s*(?:flutter\.ndkVersion|"[^"]+")/,'ndkVersion = "27.0.12077973"');
if(!g.includes("minSdk = 24"))throw new Error("Unexpected Flutter scaffold");
g+='\nandroid {\n  defaultConfig { ndk { abiFilters += "arm64-v8a" }; externalNativeBuild { cmake { arguments += "-DANDROID_STL=c++_shared" } } }\n  externalNativeBuild { cmake { path = file("src/main/cpp/CMakeLists.txt") } }\n}\n';
fs.writeFileSync(gradle,g);
console.log("Prepared isolated Flutter original-web host:",out);
console.log("No APK was built. Run flutter pub get and flutter build apk --debug --target-platform android-arm64 in the generated directory.");
