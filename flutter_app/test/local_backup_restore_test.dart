import 'dart:convert';
import 'dart:io';
import 'package:flutter_test/flutter_test.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';
import 'package:nasqo_pro_erp/services/local_database.dart';
import 'package:nasqo_pro_erp/services/local_account_commands.dart';
import 'package:nasqo_pro_erp/services/local_backup_restore.dart';
import 'package:nasqo_pro_erp/hybrid/local_snapshot_adapter.dart';

void main(){
  test('native restore, legacy SQLite review, exact archive export and rollback preserve live data',()async{
    sqfliteFfiInit();
    databaseFactory=databaseFactoryFfi;
    final dir=await Directory.systemTemp.createTemp('nasqo_backup_test_');
    await databaseFactory.setDatabasesPath(dir.path);
    final local=LocalDatabase.instance,db=await LocalDatabase.instance.database;
    final backup=LocalBackupRestore(local);
    const w='local-erp-workspace';
    final account=LocalAccountCommands(local);
    try{
      // Native test uses a real standalone database copied from empty live SQLite
      // through the application's export format, then imports a known account.
      final initial=await backup.exportNative();
      final initialFile=await File('${dir.path}/native.back').writeAsBytes(initial);
      final candidate=await backup.inspect(initialFile,'native.back');
      expect(candidate.native,isTrue);
      expect(candidate.counts['accounts'],0);
      await backup.restoreNative(candidate);
      final id=await account.save(w,'live-account',{'name':'Live account','category':'clients','currency':'ريال'});
      final live=await backup.exportNative();
      final liveFile=await File('${dir.path}/live.back').writeAsBytes(live);
      final liveCandidate=await backup.inspect(liveFile,'live.back');
      expect(liveCandidate.counts['accounts'],1);
      await expectLater(backup.restoreNative(liveCandidate),throwsStateError);
      // Empty-destination restore is still supported without a replacement lease.
      await db.transaction((t)async{
        await t.delete('bridge_idempotency_keys');
        await t.delete('sync_outbox');
        await t.delete('accounts');
      });
      // Preview mutations must not alter the verified backup payload.
      liveCandidate.nativeTables!['accounts']!.single['name']='QA mutated preview';
      await backup.restoreNative(liveCandidate);
      expect((await db.query('accounts')).single['id'],id);
      expect((await db.query('accounts')).single['name'],'Live account');
      expect((await db.rawQuery('PRAGMA integrity_check')).single.values.single,'ok');
      expect(await db.rawQuery('PRAGMA foreign_key_check'),isEmpty);
      expect(await local.pendingOperations(w),hasLength(1));
      expect(await account.save(w,'live-account',{'name':'Live account','category':'clients','currency':'ريال'}),id);
      final damaged=Map<String,dynamic>.from(jsonDecode(utf8.decode(live)) as Map);
      damaged['sha256']='bad';
      final corrupt=await File('${dir.path}/bad.back').writeAsString(jsonEncode(damaged));
      await expectLater(backup.inspect(corrupt,'bad.back'),throwsFormatException);
      final legacyPath='${dir.path}/legacy.back';
      final source=await databaseFactoryFfi.openDatabase(legacyPath);
      await source.execute('CREATE TABLE customers (id INTEGER PRIMARY KEY,name TEXT,type INTEGER,lim REAL)');
      await source.execute('CREATE TABLE stores (id INTEGER PRIMARY KEY,name TEXT,details TEXT)');
      await source.execute('CREATE TABLE products (id INTEGER PRIMARY KEY,name TEXT,price REAL,price2 REAL,unit TEXT)');
      await source.execute('CREATE TABLE currencies (id INTEGER PRIMARY KEY,name TEXT,amount REAL)');
      await source.execute('CREATE TABLE input_move (id INTEGER PRIMARY KEY,per_id INTEGER,dain REAL,madin REAL,cur INTEGER,bill_type INTEGER,year INTEGER,month INTEGER,day INTEGER)');
      await source.execute('CREATE TABLE bill_details (id INTEGER PRIMARY KEY,bill_id INTEGER,prod_id INTEGER,amount REAL,price REAL,total REAL)');
      await source.insert('customers',{'id':1,'name':'Archived client','type':2,'lim':0});
      await source.insert('stores',{'id':1,'name':'Warehouse','details':''});
      await source.insert('products',{'id':1,'name':'Old product','price':5,'price2':3,'unit':'piece'});
      await source.insert('currencies',{'id':1,'name':'ريال','amount':1});
      await source.insert('input_move',{'id':1,'per_id':1,'dain':10,'madin':2,'cur':1,'bill_type':2,'year':2026,'month':11,'day':24});
      await source.insert('bill_details',{'id':1,'bill_id':1,'prod_id':1,'amount':2,'price':5,'total':10});
      await source.close();
      final legacyFile=File(legacyPath),original=await legacyFile.readAsBytes();
      final legacy=await backup.inspect(legacyFile,'legacy.back');
      expect(legacy.native,isFalse);
      expect(legacy.counts['accounts'],1);
      expect(legacy.meta['ambiguousMoves'],1);
      await backup.openReview(legacy);
      await backup.openReview(legacy);
      expect(await db.query('backup_review_sources'),hasLength(1));
      expect(await backup.exportReviewSource(),orderedEquals(original));
      final readiness=await backup.reviewReadiness();
      expect(readiness['counts']['accounts'],1);
      expect(readiness['counts']['ledger'],1);
      expect(readiness['invoiceLines'],1);
      expect(readiness['issues']['unverifiedInventory'],1);
      expect(readiness['issues']['ambiguousSides'],1);
      expect(readiness['liveCounts']['accounts'],1);
      expect(readiness['readyForActivation'],false);
      expect(readiness['journalReconciled'],false);
      expect(await backup.exportReviewSource(),orderedEquals(original));
      final archivedInventoryBefore=await db.query('backup_review_rows',where:'collection = ?',whereArgs:['inventory']);
      final snap=await HybridLocalSnapshotAdapter.readFromDevice();
      expect((snap['accounts'] as List).single['name'],'Archived client');
      expect((snap['ledger'] as List).single['rawDain'],10);
      expect((snap['ledger'] as List).single['rawMadin'],2);
      expect((snap['ledger'] as List).single['postingStatus'],'historical_unposted');
      expect((snap['inventory'] as List).single['quantityUnverified'],true);
      expect((snap['inventory'] as List).single['legacyCatalogCost'],3);
      expect((snap['inventory'] as List).single['avgCost'],3);
      expect((snap['inventory'] as List).single['quantity'],0);
      expect(await db.query('backup_review_rows',where:'collection = ?',whereArgs:['inventory']),archivedInventoryBefore);
      expect(await db.query('inventory_items'),isEmpty);
      expect(await db.query('legacy_stock_openings'),isEmpty);
      expect(await db.query('stock_movements'),isEmpty);
      expect((snap['capabilities'] as Map)['localDocumentPosting'],isNull);
      final detail=await db.transaction((t)=>LocalBackupRestore.reviewInvoice(t,'legacy-ent-1'));
      expect((detail!['lines'] as List).single['quantity'],2);
      await expectLater(account.save(w,'blocked',{'name':'Blocked','category':'clients','currency':'ريال'}),throwsStateError);
      expect((await db.query('accounts')).single['id'],id);
      await backup.closeReview();
      final current=await HybridLocalSnapshotAdapter.readFromDevice();
      expect((current['accounts'] as List).single['name'],'Live account');
      expect(await local.pendingOperations(w),hasLength(1));
      final webPath='${dir.path}/unified.sqlite';
      final web=await databaseFactoryFfi.openDatabase(webPath);
      await web.execute('CREATE TABLE workspaces(id TEXT PRIMARY KEY,company_name TEXT,default_currency TEXT)');
      await web.execute('CREATE TABLE accounts(id TEXT PRIMARY KEY,workspace_id TEXT,name TEXT,category TEXT,opening_balance REAL,credit_limit REAL)');
      await web.execute('CREATE TABLE warehouses(id TEXT PRIMARY KEY,workspace_id TEXT,name TEXT)');
      await web.execute('CREATE TABLE inventory_items(id TEXT PRIMARY KEY,workspace_id TEXT,name TEXT,quantity REAL,avg_cost REAL,quantity_unverified INTEGER,count2 REAL,count3 REAL,warehouse_id TEXT,unit TEXT)');
      await web.execute('CREATE TABLE ledger_entries(id TEXT PRIMARY KEY,workspace_id TEXT,account_id TEXT,kind TEXT,direction TEXT,doc_type INTEGER,deleted INTEGER,posting_status TEXT,amount REAL)');
      await web.execute('CREATE TABLE invoice_lines(id INTEGER PRIMARY KEY,workspace_id TEXT,entry_id TEXT,inventory_item_id TEXT,line_kind TEXT,quantity REAL,price REAL,total REAL,unit_num INTEGER,bonus REAL)');
      await web.insert('workspaces',{'id':'ws','company_name':'Web backup','default_currency':'ريال'});
      await web.insert('accounts',{'id':'a','workspace_id':'ws','name':'Client','category':'clients','opening_balance':5,'credit_limit':0});
      await web.insert('warehouses',{'id':'wh','workspace_id':'ws','name':'Main'});
      await web.insert('inventory_items',{'id':'i','workspace_id':'ws','name':'Item','quantity':999,'avg_cost':2,'quantity_unverified':1,'count2':12,'count3':2,'warehouse_id':'wh','unit':'piece'});
      await web.insert('ledger_entries',{'id':'purchase','workspace_id':'ws','account_id':'a','kind':'invoice','direction':'credit','doc_type':3,'deleted':0,'posting_status':'posted','amount':24});
      await web.insert('ledger_entries',{'id':'sale','workspace_id':'ws','account_id':'a','kind':'invoice','direction':'debit','doc_type':2,'deleted':0,'posting_status':'posted','amount':10});
      await web.insert('invoice_lines',{'id':1,'workspace_id':'ws','entry_id':'purchase','inventory_item_id':'i','line_kind':'item','quantity':2,'price':12,'total':24,'unit_num':2,'bonus':1});
      await web.insert('invoice_lines',{'id':2,'workspace_id':'ws','entry_id':'sale','inventory_item_id':'i','line_kind':'item','quantity':1,'price':10,'total':10,'unit_num':2,'bonus':0});
      await web.close();
      final unified=await backup.inspect(File(webPath),'unified.sqlite');
      final product=unified.collections['inventory']!.single;
      expect(product['quantity'],999);
      expect(product['computedQuantity'],13);
      expect(unified.meta['invoiceLines'],2);
      await backup.openReview(unified);
      final view=await HybridLocalSnapshotAdapter.readFromDevice();
      expect((view['inventory'] as List).single['computedQuantity'],13);
      expect((view['inventory'] as List).single['legacyCatalogCost'],2);
      expect((view['inventory'] as List).single['quantityUnverified'],true);
      expect((view['inventory'] as List).single['quantity'],999);
      await backup.closeReview();
    }finally{await db.close();await dir.delete(recursive:true);}
  });
}
